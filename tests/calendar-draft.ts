import assert from "node:assert/strict";
import { reconcileCalendarDraft } from "../src/lib/calendar-draft.ts";
import type { Post } from "../src/lib/posts.ts";
const baseline = { id: "post-a", client_id: "client-a", title: "Original", caption: "Original", scheduled_date: "2026-12-15", scheduled_time: "14:00:00", status: "approved", updated_at: "v1", content_revision: 1 } as Post;
const draft = { ...baseline, title: "Draft title", caption: "Unsaved caption", scheduled_time: "15:00:00" };
const moved = { ...baseline, scheduled_date: "2026-12-16", status: "review", updated_at: "v2", content_revision: 2 } as Post;
const result = reconcileCalendarDraft(draft, baseline, moved, true);
assert.equal(result.draft.caption, "Unsaved caption");
assert.equal(result.draft.title, "Draft title");
assert.equal(result.draft.client_id, "client-a");
assert.equal(result.draft.scheduled_date, "2026-12-16");
assert.equal(result.draft.scheduled_time, "15:00:00", "monthly move must preserve unsaved time when the persisted time did not change");
assert.equal(result.draft.status, "review", "approval invalidation must override a stale draft status");
assert.equal(result.baseline.caption, "Original");
assert.equal(result.baseline.updated_at, "v2");
const media = reconcileCalendarDraft({ ...draft, scheduled_date: "2026-12-20" }, baseline, { ...baseline, status: "review", updated_at: "v2" }, false);
assert.equal(media.draft.scheduled_date, "2026-12-20", "media upload must not erase the draft date");
assert.equal(media.draft.scheduled_time, "15:00:00");
const explicitTime = reconcileCalendarDraft(draft, baseline, { ...moved, scheduled_time: "16:00:00" }, true);
assert.equal(explicitTime.draft.scheduled_time, "16:00:00");
console.log("PASS: drag/media revision merges preserve draft fields, original account and pending time; explicit time and new approval state reconcile safely");
